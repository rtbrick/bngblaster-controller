const (
	// DefaultConfigFolder is the default config folder.
	DefaultConfigFolder = "/var/bngblaster"

	// DefaultExecutable is the default executable for bngblaster.
	DefaultExecutable = "/usr/bin/bngblaster"

	// permission file and folder permissions to use.
	permission os.FileMode = 0o777

	readTimeout                = 5 * time.Second
	writeTimeout               = 5 * time.Second
	bufferLength               = 512
	initialReceiveBufferLength = 20000

	// startupPollInterval is how often Start polls the control socket
	// while waiting to see whether bngblaster came up successfully.
	startupPollInterval = 100 * time.Millisecond

	// exitStartupAborted is the exit status of bngblaster if its startup
	// was aborted by a teardown request (test-stop or a signal).
	exitStartupAborted = 3
	// exitSignalBase plus the signal number is the exit code of a process
	// terminated by a signal, as shells and docker report it.
	exitSignalBase = 128

	// ConfigFilename configuration file of the blaster.
	ConfigFilename = "config.json"
	// runPidFilename file that contains the process id of the bngblaster instance if it is running.
	runPidFilename = "run.pid"
	// runPidTempFilename is the temporary file run.pid is written to
	// before it is renamed into place (see writePidFile).
	runPidTempFilename = ".run.pid.tmp"
	// RunLogFilename file that contains the logs of the execution.
	RunLogFilename = "run.log"
	// RunConfigFilename configuration of one run.
	RunConfigFilename = "run.json"
	// RunReportFilename result report generated after the test.
	RunReportFilename = "run_report.json"
	// RunPcapFilename optional traffic capture generated by the bngblaster itself.
	RunPcapFilename = "run.pcap"
	// RunSockFilename control socket.
	RunSockFilename = "run.sock"
	// RunStdErr redirected standard error output of the bngblaster.
	RunStdErr = "run.stderr"
	// RunStdOut redirected standard output of the bngblaster.
	RunStdOut = "run.stdout"
)

// IsRunFile reports whether name is one of the files the controller itself
// writes into an instance folder for a run. Uploads must never replace
// these: run.pid in particular decides which process _stop and _kill signal,
// and the controller runs as root.
func IsRunFile(name string) bool {
	switch name {
	case runPidFilename, RunSockFilename, RunConfigFilename, RunLogFilename,
		RunReportFilename, RunPcapFilename, RunStdErr, RunStdOut:
		return true
	}
	return false
}

// IsReservedFile reports whether name must not be used for a file put into
// an instance folder from outside (an upload): the run files and the
// temporary files of a generator run, which the next run would remove or
// move into place.
func IsReservedFile(name string) bool {
	return IsRunFile(name) || generator.IsTempName(name)
}

// IsHiddenFile reports whether name is a file of an instance folder that is
// neither listed nor downloadable: the pid file (and the temporary file it
// is written to) and the control socket, which are internal, and the
// temporary files of a running generator, which are incomplete by
// definition.
func IsHiddenFile(name string) bool {
	return name == runPidFilename || name == runPidTempFilename || name == RunSockFilename || generator.IsTempName(name)
}

