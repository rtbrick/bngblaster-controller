// validInstanceName reports whether name is a plain folder name below the
// config folder. The server already sanitizes names; this keeps the
// methods that write, start or remove an instance from ever acting on the
// config folder itself (an empty name) or outside of it, whatever the
// caller passes.
func validInstanceName(name string) bool {
	return name != "" && name != "." && name != ".." && !strings.ContainsAny(name, "/\x00")
}

// Create implements Repository.
func (r *DefaultRepository) Create(name string, config []byte) error {
	if !validInstanceName(name) {
		return ErrInvalidInstanceName
	}
	if r.Running(name) {
		return ErrBlasterRunning
	}
	folder := path.Join(r.configFolder, name)
	if err := os.MkdirAll(folder, permission); err != nil {
		return err
	}

	file := path.Join(folder, ConfigFilename)
	if err := os.WriteFile(file, config, permission); err != nil {
		return err
	}
	if err := r.cleanupRunFiles(name, false); err != nil {
		return err
	}
	return nil
}

// Delete implements Repository.
func (r *DefaultRepository) Delete(name string) error {
	if !validInstanceName(name) {
		return ErrInvalidInstanceName
	}
	if r.Running(name) {
		return ErrBlasterRunning
	}
	folder := path.Join(r.configFolder, name)
	// Removing the folder under a running generator would make it fail
	// in confusing ways (or recreate files in a deleted folder).
	if !generating.tryLock(folder) {
		return ErrGeneratorBusy
	}
	defer generating.unlock(folder)
	_ = os.RemoveAll(folder)
	exits.clear(folder)
	return nil
}

// generating holds the instance folders a generator currently runs in.
// It is keyed by folder rather than kept per repository since the folder
// is the shared resource, whichever repository value refers to it.
var generating = folderLocks{busy: map[string]struct{}{}}

// folderLocks is a set of non-blocking per-folder locks: a second request
// for a busy folder is rejected instead of queued, since a generator can
// run for minutes.
type folderLocks struct {
	mu   sync.Mutex
	busy map[string]struct{}
}

// tryLock locks folder unless it is locked already.
func (l *folderLocks) tryLock(folder string) bool {
	l.mu.Lock()
	defer l.mu.Unlock()
	if _, ok := l.busy[folder]; ok {
		return false
	}
	l.busy[folder] = struct{}{}
	return true
}

// unlock releases a lock taken by tryLock.
func (l *folderLocks) unlock(folder string) {
	l.mu.Lock()
	defer l.mu.Unlock()
	delete(l.busy, folder)
}

// Generate implements Repository.
func (r *DefaultRepository) Generate(ctx context.Context, name string, executable string, job generator.Job) (generator.Result, error) {
	folder := path.Join(r.configFolder, name)
	if !generating.tryLock(folder) {
		return generator.Result{}, ErrGeneratorBusy
	}
	defer generating.unlock(folder)
	// Checked under the lock, which Delete takes as well, so the folder
	// cannot disappear between the check and the run.
	if !r.Exists(name) {
		return generator.Result{}, ErrBlasterNotExists
	}
	return generator.Run(ctx, folder, executable, job, func() bool { return !r.Running(name) })
}

// RemoveGeneratorTempFiles removes the temporary files a generator run
// left behind in any instance folder, e.g. because the controller was
// restarted while a tool was running. It is meant to be called once at
// startup, before any request is served.
func (r *DefaultRepository) RemoveGeneratorTempFiles() {
	for _, name := range r.Instances() {
		generator.RemoveTempFiles(path.Join(r.configFolder, name))
	}
}

// exits holds the exit code of the last run of each instance folder, for
// as long as this controller runs. Like generating, it is keyed by folder.
// It is deliberately not persisted: after a controller restart, a code
// found in a (persistent) instance folder could belong to any earlier run.
var exits = exitCodes{codes: map[string]int{}}

// exitCodes maps instance folders to the exit code of their last run.
type exitCodes struct {
	mu    sync.Mutex
	codes map[string]int
}

func (e *exitCodes) set(folder string, code int) {
	e.mu.Lock()
	defer e.mu.Unlock()
	e.codes[folder] = code
}

func (e *exitCodes) get(folder string) (int, bool) {
	e.mu.Lock()
	defer e.mu.Unlock()
	code, ok := e.codes[folder]
	return code, ok
}

func (e *exitCodes) clear(folder string) {
	e.mu.Lock()
	defer e.mu.Unlock()
	delete(e.codes, folder)
}

// exitCode converts the result of waiting for a process into its exit
// code, reporting a termination by signal n as 128+n like a shell (and
// docker) does. ok is false if the process could not be waited for.
func exitCode(waitErr error) (int, bool) {
	if waitErr == nil {
		return 0, true
	}
	var exitErr *exec.ExitError
	if !errors.As(waitErr, &exitErr) {
		return 0, false
	}
	if status, ok := exitErr.Sys().(syscall.WaitStatus); ok && status.Signaled() {
		return exitSignalBase + int(status.Signal()), true
	}
	return exitErr.ExitCode(), true
}

// cleanupRunFiles removes the files of the previous run. keepRunConfig
// leaves run.json alone, for Start, which writes it anyway.
func (r *DefaultRepository) cleanupRunFiles(name string, keepRunConfig bool) error {
	folder := path.Join(r.configFolder, name)
	exits.clear(folder)
	files := []string{
		path.Join(folder, runPidFilename),
		path.Join(folder, RunLogFilename),
		path.Join(folder, RunReportFilename),
		path.Join(folder, RunPcapFilename),
		path.Join(folder, RunSockFilename),
		path.Join(folder, RunStdErr),
		path.Join(folder, RunStdOut),
	}
	if !keepRunConfig {
		files = append(files, path.Join(folder, RunConfigFilename))
	}
	files = append(files, rotatedLogs(folder)...)
	for _, f := range files {
		if err := os.Remove(f); err != nil {
			if os.IsNotExist(err) {
				continue
			}
			return err
		}
	}
	return nil
}

// rotatedLogs returns the copies of run.log that a log rotation (e.g.
// logrotate) left in folder: run.log.1, run.log.2.gz, run.log-20261028
// and the like. They belong to the run whose log they continue, so they
// go together with run.log instead of piling up across runs.
func rotatedLogs(folder string) []string {
	entries, err := os.ReadDir(folder)
	if err != nil {
		return nil
	}
	var files []string
	for _, entry := range entries {
		name := entry.Name()
		if !entry.IsDir() && (strings.HasPrefix(name, RunLogFilename+".") || strings.HasPrefix(name, RunLogFilename+"-")) {
			files = append(files, path.Join(folder, name))
		}
	}
	return files
}

// Instances implements Repository.
func (r *DefaultRepository) Instances() []string {
	instances := []string{}
	entries, err := os.ReadDir(r.configFolder)
	if err != nil {
		return instances // Return the empty slice if there's an error.
	}
	for _, entry := range entries {
		if entry.IsDir() {
			instances = append(instances, entry.Name())
		}
	}
	return instances
}

// Exists implements Repository.
func (r *DefaultRepository) Exists(name string) bool {
	folder := path.Join(r.configFolder, name)
	if _, err := os.Stat(folder); os.IsNotExist(err) {
		return false
	}
	return true
}

// pid returns the process id recorded in the instance's pid file.
//
// Only values above 1 are accepted: the pid is handed straight to kill(2),
// where 0 and negative values address whole process groups (-1 is every
// process) and 1 is init - none of which can ever be a bngblaster instance,
// whatever ended up in the file.
func (r *DefaultRepository) pid(name string) (int, bool) {
	piddata, err := os.ReadFile(path.Join(r.configFolder, name, runPidFilename))
	if err != nil {
		return 0, false
	}
	pid, err := strconv.Atoi(strings.TrimSpace(string(piddata)))
	if err != nil || pid <= 1 {
		return 0, false
	}
	return pid, true
}

// Running implements Repository.
func (r *DefaultRepository) Running(name string) bool {
	file := path.Join(r.configFolder, name, runPidFilename)
	if _, err := os.Stat(file); os.IsNotExist(err) {
		return false
	}
	pid, ok := r.pid(name)
	if ok && isInstanceProcess(pid, path.Join(r.configFolder, name, RunSockFilename)) {
		return true
	}
	// run.pid is only removed once its process is gone (or it holds no
	// valid pid). A live process that is not recognized as the instance -
	// a pid reused after a reboot, or a check that failed for a moment -
	// counts as not running, but keeps the file: removing it would lose a
	// running instance for good if the check was wrong, and the next start
	// replaces the file anyway.
	if ok && processAlive(pid) {
		return false
	}
	_ = os.Remove(file)
	return false
}

// processAlive reports whether a process with this pid exists.
func processAlive(pid int) bool {
	err := syscall.Kill(pid, 0)
	return err == nil || errors.Is(err, syscall.EPERM)
}

// instancePid returns the pid from the instance's run.pid if that process
// is the bngblaster started for this instance. A live pid alone proves
// nothing: run.pid survives a reboot or container restart in the
// persistent config folder, and its pid may since belong to any other
// process - which, the controller running as root, Kill would then
// SIGKILL.
func (r *DefaultRepository) instancePid(name string) (int, bool) {
	pid, ok := r.pid(name)
	if !ok || !isInstanceProcess(pid, path.Join(r.configFolder, name, RunSockFilename)) {
		return 0, false
	}
	return pid, true
}

// isInstanceProcess reports whether process pid is the bngblaster serving
// socket. A variable so tests can stand in their own process for one.
var isInstanceProcess = procIsInstanceProcess

// procIsInstanceProcess identifies the process by its command line: every
// bngblaster the controller starts (see commandlineParameters) carries
// "-S <instance folder>/run.sock", which no other process has. A process
// that is gone or cannot be read is not the instance.
//
// The command line is empty right after the process was started, until
// the kernel has set up the new program - and the controller checks the
// instance just then. That takes microseconds on an idle host, but can
// take much longer on one whose CPUs are busy with the I/O threads of
// other instances. So an empty command line is not a mismatch: such a
// process is still starting and counts as the instance, unless it is a
// zombie or a kernel thread (which keep an empty one). A reused pid of
// any other process has its command line.
func procIsInstanceProcess(pid int, socket string) bool {
	cmdline, err := os.ReadFile(fmt.Sprintf("/proc/%d/cmdline", pid))
	if err != nil {
		return false
	}
	if len(cmdline) == 0 {
		return procStarting(pid)
	}
	want, err := filepath.Abs(socket)
	if err != nil {
		return false
	}
	args := strings.Split(strings.TrimSuffix(string(cmdline), "\x00"), "\x00")
	for i := 0; i+1 < len(args); i++ {
		if args[i] != "-S" {
			continue
		}
		if got, err := filepath.Abs(args[i+1]); err == nil && got == want {
			return true
		}
	}
	return false
}

// pfKthread is the PF_KTHREAD flag of /proc/<pid>/stat: a kernel thread.
const pfKthread = 0x00200000

// procStarting reports whether process pid, whose command line is empty,
// is a process that is still starting: neither a zombie nor a kernel
// thread. A process whose state cannot be read is not.
func procStarting(pid int) bool {
	stat, err := os.ReadFile(fmt.Sprintf("/proc/%d/stat", pid))
	if err != nil {
		return false
	}
	// "pid (comm) state ppid pgrp session tty_nr tpgid flags ...": comm
	// may itself contain ") ".
	i := bytes.LastIndexByte(stat, ')')
	if i < 0 {
		return false
	}
	fields := strings.Fields(string(stat[i+1:]))
	if len(fields) < 7 || fields[0] == "Z" {
		return false
	}
	flags, err := strconv.ParseUint(fields[6], 10, 64)
	return err == nil && flags&pfKthread == 0
}

// Start implements Repository.
func (r *DefaultRepository) Start(ctx context.Context, name string, runningConfig RunningConfig) error {
	if !validInstanceName(name) {
		return ErrInvalidInstanceName
	}
	if !r.Exists(name) {
		return ErrBlasterNotExists
	}
	if r.Running(name) {
		return ErrBlasterRunning
	}
	// Validate before touching any run file, so a rejected request leaves
	// the previous run's report and logs in place.
	params, err := r.commandlineParameters(name, runningConfig)
	if err != nil {
		return err
	}
	if err := r.cleanupRunFiles(name, true); err != nil {
		return err
	}
	folder := path.Join(r.configFolder, name)
	if err := writeRunConfig(path.Join(folder, RunConfigFilename), runningConfig); err != nil {
		return err
	}
	// folder as the working directory lets bngblaster resolve any relative
	// file reference in config.json (e.g. an isis mrt-file or a bgp
	// raw-update-file) against the instance directory, which is also where
	// uploaded files are stored.
	done, err := RunCommand(
		folder,
		path.Join(folder, runPidFilename),
		path.Join(folder, RunStdOut),
		path.Join(folder, RunStdErr),
		params...)
	if err != nil {
		return err
	}

	return waitForStartup(ctx, folder, done)
}

// writeRunConfig stores the start arguments of a run as run.json, unless
// the file already holds the same arguments. That is the case when an
// instance is started from its own run.json (see Autostart), which may be
// a file mounted read-only into a container: replacing it would fail.
func writeRunConfig(file string, runningConfig RunningConfig) error {
	if current, err := ReadRunConfig(file); err == nil && reflect.DeepEqual(current, runningConfig) {
		return nil
	}
	config, err := json.Marshal(runningConfig)
	if err != nil {
		return err
	}
	return os.WriteFile(file, config, permission)
}

// ReadRunConfig reads the start arguments stored in a run.json file. It
// decodes them the same way the _start API decodes its request body.
func ReadRunConfig(file string) (RunningConfig, error) {
	var runningConfig RunningConfig
	f, err := os.Open(file)
	if err != nil {
		return runningConfig, err
	}
	defer f.Close()
	err = json.NewDecoder(f).Decode(&runningConfig)
	return runningConfig, err
}

// waitForStartup waits for a freshly spawned bngblaster to either come up
// or fail, returning its stderr output as the error in the latter case and
// ErrBlasterStartupAborted if the startup was aborted.
//
// A bad configuration makes bngblaster print an error and exit - usually
// within milliseconds, but a large configuration can take a while to
// either come up or fail, and an instance can wait for minutes for the
// startup of other instances (the startup lock). So there is deliberately
// no deadline: the wait ends when the instance is up, when it has exited,
// or when ctx is done - a caller that has gone away (a disconnected HTTP
// client) stops the wait immediately instead of pinning a goroutine for
// it. A startup that takes too long is aborted by stopping or killing the
// instance, which ends the wait through its exit.
//
// How "came up" is detected depends on the bngblaster version. Older
// versions create the control socket only once fully up, so the socket
// appearing is enough. Newer versions open it right after the log file,
// before the configuration is even loaded, and instead report the startup
// through the "status" field of test-info; for those the wait continues
// until the status leaves "starting". A test-info without "status" marks
// an older version.
//
// Note that returning early never stops the instance: it has been
// spawned either way, and giving up on *observing* the outcome only
// means the caller has to ask for the status separately.
func waitForStartup(ctx context.Context, folder string, done <-chan error) error {
	sockFile := path.Join(folder, RunSockFilename)
	ticker := time.NewTicker(startupPollInterval)
	defer ticker.Stop()
	for {
		select {
		case <-ctx.Done():
			// Caller gave up waiting; the instance itself keeps running.
			return nil
		case waitErr := <-done:
			if waitErr == nil {
				// Exited on its own without an error before coming up:
				// not the failure case this is guarding against.
				return nil
			}
			if startupAborted(waitErr) {
				return ErrBlasterStartupAborted
			}
			stderrContent, _ := os.ReadFile(path.Join(folder, RunStdErr))
			msg := strings.TrimSpace(string(stderrContent))
			if msg == "" {
				msg = waitErr.Error()
			}
			return fmt.Errorf("%s", msg)
		case <-ticker.C:
			if _, statErr := os.Stat(sockFile); statErr == nil && startupCompleted(sockFile) {
				return nil
			}
		}
	}
}

// startupAborted reports whether the exit error of an instance that has
// not come up yet is the result of an abort rather than a failure: the
// dedicated exit status of a teardown request during the startup, or a
// signal (_kill, or _stop with versions that do not handle signals during
// the startup).
func startupAborted(waitErr error) bool {
	var exitErr *exec.ExitError
	if !errors.As(waitErr, &exitErr) {
		return false
	}
	if exitErr.ExitCode() == exitStartupAborted {
		return true
	}
	status, ok := exitErr.Sys().(syscall.WaitStatus)
	return ok && status.Signaled()
}

// startupCompleted reports whether the instance behind the control socket
// has finished its startup, see waitForStartup.
//
// A failed query is retried on the next poll: the socket file exists from
// bind() on, slightly before bngblaster accepts connections. While the
// status is "stopping" the startup has failed or was aborted, and the
// process is about to exit, which waitForStartup then reports with its
// stderr output.
func startupCompleted(sockFile string) bool {
	result, err := socketCommand(sockFile, SocketCommand{Command: "test-info"})
	if err != nil {
		return false
	}
	var info TestInfoResponse
	if err := json.Unmarshal(result, &info); err != nil {
		return false
	}
	switch info.TestInfo.Status {
	case "starting", "stopping":
		return false
	default:
		// "running", or a version reporting no status at all.
		return true
	}
}

// ExitCode implements Repository.
func (r *DefaultRepository) ExitCode(name string) (int, bool) {
	if r.Running(name) {
		return 0, false
	}
	return exits.get(path.Join(r.configFolder, name))
}

// Stop implements Repository.
func (r *DefaultRepository) Stop(name string) {
	r.sendSignal(name, os.Interrupt)
}

// Terminate implements Repository.
func (r *DefaultRepository) Terminate(name string) {
	r.sendSignal(name, syscall.SIGTERM)
}

// Kill implements Repository.
func (r *DefaultRepository) Kill(name string) {
	r.sendSignal(name, os.Kill)
}

func (r *DefaultRepository) sendSignal(name string, signal os.Signal) {
	if pid, ok := r.instancePid(name); ok {
		// Look for the pid in the process list.
		if process, err := os.FindProcess(pid); err == nil {
			// Send the process a signal.
			_ = process.Signal(signal)
		}
	}
}

func (r *DefaultRepository) commandlineParameters(name string, runningConfig RunningConfig) ([]string, error) {
	folder := path.Join(r.configFolder, name)
	var params []string
	params = append(params, r.executable)
	params = append(params, "-C", path.Join(folder, ConfigFilename))
	params = append(params, "-S", path.Join(folder, RunSockFilename))
	if runningConfig.Report {
		params = append(params, "-J", path.Join(folder, RunReportFilename))
	}
	for _, flag := range runningConfig.ReportFlags {
		params = append(params, "-j", flag)
	}
	if runningConfig.Logging {
		params = append(params, "-L", path.Join(folder, RunLogFilename))
	}
	for _, flag := range runningConfig.LoggingFlags {
		params = append(params, "-l", flag)
	}
	if runningConfig.PCAPCapture {
		params = append(params, "-P", path.Join(folder, RunPcapFilename))
	}
	if runningConfig.SessionCount > 0 {
		// SessionCount has priority over the deprecated PPPoESessionCount
		params = append(params, "-c", fmt.Sprintf("%d", runningConfig.SessionCount))
	} else if runningConfig.PPPoESessionCount > 0 {
		params = append(params, "-c", fmt.Sprintf("%d", runningConfig.PPPoESessionCount))
	}
	if len(runningConfig.StreamConfig) > 0 {
		streamConfig, err := streamConfigPath(folder, runningConfig.StreamConfig)
		if err != nil {
			return nil, err
		}
		params = append(params, "-T", streamConfig)
	}
	return params, nil
}

// streamConfigPath resolves the stream configuration file of a start
// request.
//
// An absolute path is used as-is: test setups keep stream files outside
// the controller (e.g. in a home directory, next to other test material)
// and bngblaster, running as root, reads them from there just like the
// files config.json references. A relative path is resolved against the
// instance folder and must stay inside it, so "../other/streams.json"
// cannot silently reach into another instance or out of the config folder;
// whoever means a file elsewhere has to say so with an absolute path.
func streamConfigPath(folder, streamConfig string) (string, error) {
	if path.IsAbs(streamConfig) {
		return streamConfig, nil
	}
	resolved := path.Join(folder, streamConfig)
	absFolder, err := filepath.Abs(folder)
	if err != nil {
		return "", err
	}
	absResolved, err := filepath.Abs(resolved)
	if err != nil {
		return "", err
	}
	rel, err := filepath.Rel(absFolder, absResolved)
	if err != nil || rel == "." || rel == ".." || strings.HasPrefix(rel, "../") {
		return "", ErrInvalidStreamConfig
	}
	return resolved, nil
}

func (r *DefaultRepository) config(name string) ([]byte, error) {
	folder := path.Join(r.configFolder, name)
	file := path.Join(folder, ConfigFilename)
	return os.ReadFile(file)
}

// Files implements Repository.
func (r *DefaultRepository) Files(name string) ([]InstanceFile, error) {
	if !r.Exists(name) {
		return nil, ErrBlasterNotExists
	}
	folder := path.Join(r.configFolder, name)
	entries, err := os.ReadDir(folder)
	if err != nil {
		return nil, err
	}
	files := make([]InstanceFile, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() || IsHiddenFile(entry.Name()) {
			continue
		}
		info, err := entry.Info()
		if err != nil {
			continue
		}
		files = append(files, InstanceFile{Name: entry.Name(), Size: info.Size()})
	}
	return files, nil
}

// Command implements Repository.
func (r *DefaultRepository) Command(name string, command SocketCommand) ([]byte, error) {
	if !r.Exists(name) {
		return nil, ErrBlasterNotExists
	}
	if !r.Running(name) {
		return nil, ErrBlasterNotRunning
	}
	if err := checkCommandFile(command); err != nil {
		return nil, err
	}
	return socketCommand(path.Join(r.configFolder, name, RunSockFilename), command)
}

// writeFileCommands are the bngblaster control commands whose "file"
// argument names a file bngblaster creates or truncates. bngblaster runs as
// root and opens it as given, so unchecked it would overwrite any path on
// the host (e.g. a block device, or another instance's run.pid). The other
// commands taking a "file" (bgp-raw-update, isis-load-mrt, ...) only read
// it.
var writeFileCommands = map[string]bool{"pcap-start": true}

// checkCommandFile checks the "file" argument of a command that writes it:
// it must be a plain name, which bngblaster resolves against its working
// directory, the instance folder (see Start). It must not be hidden
// (generator temp files start with a dot) nor one of the files the
// controller relies on; run.pcap stays allowed, it is the regular capture
// file. Without a "file", bngblaster reuses its pcap file from the command
// line, which is in the folder already.
func checkCommandFile(command SocketCommand) error {
	if !writeFileCommands[command.Command] {
		return nil
	}
	value, ok := command.Arguments["file"]
	if !ok {
		return nil
	}
	file, ok := value.(string)
	if !ok || file == "" || strings.HasPrefix(file, ".") || strings.ContainsAny(file, "/\x00") ||
		file == ConfigFilename || (IsReservedFile(file) && file != RunPcapFilename) {
		return ErrInvalidCommandFile
	}
	return nil
}

// socketCommand sends one command to the control socket at file and returns
// the raw response. Unlike Command it does not check the pid file, so the
// startup wait can use it while the instance is still coming up.
func socketCommand(file string, command SocketCommand) ([]byte, error) {
	// Open Socket
	c, err := net.Dial("unix", file)
	if err != nil {
		return nil, err
	}
	defer func() {
		_ = c.Close()
	}()
	_ = c.SetWriteDeadline(time.Now().Add(writeTimeout))

	// Send Command
	if err := json.NewEncoder(c).Encode(command); err != nil {
		return nil, err
	}

	// Receive Response
	received := make([]byte, 0, initialReceiveBufferLength)
	_ = c.SetReadDeadline(time.Now().Add(readTimeout))
	for {
		buf := make([]byte, bufferLength)
		count, err := c.Read(buf)
		received = append(received, buf[:count]...)
		if err != nil {
			if errors.Is(err, syscall.ECONNRESET) {
				continue
			}
			if err == io.EOF {
				break
			}
			return nil, err
		}
	}

	return received, nil
}
